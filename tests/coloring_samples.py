"""Write four SYNTHETIC sample coloring books for previews and documentation.

    python tests/coloring_samples.py DIR

creates DIR/simple, DIR/detailed, DIR/sections and DIR/single-sided. Every drawing
is generated by tests/coloring_helpers.py; none is authored artwork, and nothing
here shows real-world print quality. The books are written through the artwork
library like any project, so their files are content-addressed project assets.
"""

import sys
from pathlib import Path

from PIL import Image, ImageDraw

sys.path.insert(0, str(Path(__file__).resolve().parent))

from coloring_helpers import (  # noqa: E402
    FULL_SIZE,
    dense_pattern,
    encode,
    fine_detail,
    light_colored_lines,
    line_art,
    noisy_scan,
    pencil_sketch,
    white_on_black,
    write_coloring_book,
)

from puzzlepress import dump_project, validate_project  # noqa: E402
from puzzlepress.coloring.library import import_files  # noqa: E402
from puzzlepress.project import load_project  # noqa: E402

COPYRIGHT = (
    "Copyright 2026 Sample Author. All rights reserved.\n"
    "Synthetic sample book generated by PuzzlePress tests; not for sale."
)
INSTRUCTIONS = (
    "Each drawing is printed on its own page. Use colored pencils or crayons; markers may "
    "bleed through thin paper."
)


def bold(seed: int) -> Image.Image:
    """A simple drawing with thick, child-friendly outlines."""
    return line_art(seed, FULL_SIZE, line=18)


def mandala(seed: int) -> Image.Image:
    """Concentric rings and spokes: fine, regular detail."""
    image = Image.new("L", FULL_SIZE, 255)
    draw = ImageDraw.Draw(image)
    cx, cy = FULL_SIZE[0] // 2, FULL_SIZE[1] // 2
    for ring in range(1, 9):
        r = ring * 120 + seed * 7
        draw.ellipse((cx - r, cy - r, cx + r, cy + r), outline=0, width=3 + ring % 3)
    for spoke in range(0, 360, 15):
        import math

        a = math.radians(spoke + seed)
        draw.line(
            (cx, cy, cx + round(1000 * math.cos(a)), cy + round(1000 * math.sin(a))),
            fill=0,
            width=2,
        )
    return image


def _write(
    directory: Path,
    title: str,
    drawings: list[tuple[str, Image.Image, dict[str, object]]],
    *,
    front: list[dict[str, object]],
    dividers: dict[int, tuple[str, str | None]],
    reverse: bool,
    border: str,
    numbers: dict[str, object],
    back: list[dict[str, object]] | None = None,
) -> Path:
    write_coloring_book(directory)
    import_files(directory, [(f"{name}.png", encode(image)) for name, image, _ in drawings])
    data = load_project(directory).project.to_dict()
    book = data["book"]
    assert isinstance(book, dict)
    book.update({"title": title, "author": "Sample Author", "id": directory.name})
    # Builds go beside the book, inside the samples folder, never into build/.
    data["output"] = {"directory": f"../build-{directory.name}"}
    coloring = data["coloring"]
    assert isinstance(coloring, dict)
    for entry, (_, _, adjust) in zip(coloring["artwork"], drawings, strict=True):
        entry["adjustments"].update(adjust)
    pages: list[object] = []
    for position, page in enumerate(coloring["pages"]):
        if position in dividers:
            heading, text = dividers[position]
            pages.append({"divider": {"title": heading, **({"text": text} if text else {})}})
        pages.append(page)
    coloring["pages"] = pages
    coloring["layout"] = {"blank_reverse": reverse, "border": border}
    data["composition"] = {
        "front_matter": front,
        "artwork": {"start": "recto"},
        "back_matter": back or [],
        "page_numbers": numbers,
    }
    project = validate_project(data).require_project()
    (directory / "book.yaml").write_text(dump_project(project), encoding="utf-8")
    return directory


def write_samples(root: Path) -> dict[str, Path]:
    title = {"kind": "title_page"}
    copyright_page = {"kind": "copyright_page", "text": COPYRIGHT}
    instructions = {"kind": "instructions", "title": "How to use this book", "text": INSTRUCTIONS}
    books = {
        # 1. Bold drawings printed on both sides of the paper.
        "simple": _write(
            root / "simple",
            "Simple Shapes to Color",
            [(f"shapes {n}", bold(n), {}) for n in range(1, 7)],
            front=[title, copyright_page],
            dividers={},
            reverse=False,
            border="none",
            numbers={},
        ),
        # 2. Fine and difficult drawings, each with the settings it needs.
        "detailed": _write(
            root / "detailed",
            "Detailed Line Art",
            [
                ("fine detail", fine_detail(), {}),
                ("mandala", mandala(3), {}),
                ("dense pattern", dense_pattern(), {}),
                ("pencil sketch", pencil_sketch(5), {"contrast": 2.5, "background_cleanup": 0.4}),
                ("scanned page", noisy_scan(7), {"background_cleanup": 0.6, "despeckle": 4}),
                ("yellow lines", light_colored_lines(8), {"grayscale": False}),
                ("white on black", white_on_black(9), {"invert": True}),
            ],
            front=[title, copyright_page, instructions],
            dividers={},
            reverse=True,
            border="thin",
            numbers={},
        ),
        # 3. Front matter and three sections, each opened by a divider.
        "sections": _write(
            root / "sections",
            "Three Habitats",
            [(f"habitat {n}", line_art(20 + n, FULL_SIZE, line=10), {}) for n in range(9)],
            front=[title, copyright_page, instructions],
            dividers={
                0: ("Woodland", "Foxes, owls and ferns."),
                3: ("Ocean", "Waves, shells and fish."),
                6: ("Garden", None),
            },
            reverse=True,
            border="double",
            numbers={"scheme": "roman_front_matter", "show_front_matter": True},
            back=[{"kind": "notes", "title": "Notes"}],
        ),
        # 4. Single-sided: every drawing on a right-hand page, backed by a blank page.
        "single-sided": _write(
            root / "single-sided",
            "One Side Only",
            [(f"page {n}", line_art(40 + n, FULL_SIZE, line=12), {}) for n in range(5)],
            front=[title, copyright_page],
            dividers={},
            reverse=True,
            border="none",
            numbers={"show_artwork": False},
        ),
    }
    return books


if __name__ == "__main__":
    for name, path in write_samples(Path(sys.argv[1])).items():
        print(f"{name}: {path}")
