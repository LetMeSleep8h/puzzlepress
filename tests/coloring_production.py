"""A SYNTHETIC coloring book with a cover and publishing metadata, for tests and docs.

    python tests/coloring_production.py DIRECTORY

writes DIRECTORY/book (the project) and builds its interior into DIRECTORY/build
to size the cover. Every drawing is generated by tests/coloring_helpers.py; none is
authored artwork. The publishing section carries SYNTHETIC declarations and
confirmations made for no real author, so the book can reach a ready package in
tests: real books must have their own author's declarations. Nothing here shows
real-world print quality.
"""

import copy
import sys
from dataclasses import replace
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from coloring_helpers import encode, line_art  # noqa: E402

from puzzlepress import dump_project, validate_project  # noqa: E402
from puzzlepress.coloring.library import import_files  # noqa: E402
from puzzlepress.project import load_project  # noqa: E402

BOOK_ID = "synthetic-coloring-production"
TITLE = "Synthetic Shapes to Color"
DRAWINGS = 12
PAGE_TEXT = "Twelve drawings to color, {page_count} pages, {trim_size}"
DESCRIPTION = (
    "Twelve synthetic outline drawings, each printed on its own right-hand page with a "
    "blank back so markers do not show through. Generated for PuzzlePress tests; not for sale."
)


def source() -> dict[str, object]:
    return {
        "schema_version": 1,
        "book": {
            "id": BOOK_ID,
            "title": TITLE,
            "subtitle": "A Test Book",
            "author": "Sample Author",
            "language": "en",
        },
        "build": {"seed": 1},
        "output": {"directory": f"../../build/{BOOK_ID}"},
        "coloring": {"version": 1, "layout": {"blank_reverse": True, "border": "thin"}},
        "composition": {
            "front_matter": [
                {"kind": "title_page"},
                {
                    "kind": "copyright_page",
                    "text": "Copyright 2026 Sample Author. Synthetic test book; not for sale.",
                },
                {
                    "kind": "instructions",
                    "title": "How to Use This Book",
                    "text": "Color each drawing however you like.",
                },
            ],
            "artwork": {"start": "recto"},
            "back_matter": [],
            "page_numbers": {"scheme": "continuous", "show_artwork": False},
        },
    }


def publishing(**overrides: object) -> dict[str, object]:
    """A complete coloring publishing section; `confirm` values are filled in later."""
    section: dict[str, object] = {
        "version": 2,
        "description": DESCRIPTION,
        "keywords": ["synthetic shapes coloring", "outline drawings"],
        "categories": ["Crafts, Hobbies & Home > Coloring Books for Grown-Ups"],
        "contributors": [],
        "audience": {"sexually_explicit": False, "reading_age": {"minimum": None, "maximum": None}},
        "low_content": False,
        "isbn": {"mode": "kdp_free", "value": None},
        "edition": 1,
        "series": None,
        # SYNTHETIC: declared for no real author.
        "ai_disclosure": {
            "text": "human",
            "images": "human",
            "translations": "none",
            "interior_artwork": "human",
            "cover_artwork": "none",
        },
        "content_rights": {
            "interior_artwork": "own_work",
            "cover_artwork": "none",
            "text": "own_work",
            "notes": "Synthetic test declarations.",
        },
        "attestations": {"rights": None, "ai_disclosure": None, "metadata": None, "isbn": None},
        "notes": None,
    }
    section.update(copy.deepcopy(overrides))
    return section


def confirm_all(
    directory: Path, names: tuple[str, ...] = ("rights", "ai_disclosure", "metadata")
) -> None:
    """Record SYNTHETIC confirmations of the current content in DIRECTORY/book.yaml."""
    from puzzlepress.publishing.review import review_identity

    loaded = load_project(directory)
    project = loaded.project
    assert project.publishing is not None
    attestations = replace(
        project.publishing.attestations,
        **{name: review_identity(project, name) for name in names},
    )
    updated = replace(project, publishing=replace(project.publishing, attestations=attestations))
    loaded.source_path.write_text(dump_project(updated), encoding="utf-8")


def write_book(directory: Path, confirm: bool = True, cover: bool = True) -> Path:
    """Write the book into DIRECTORY/book and build its interior into DIRECTORY/build."""
    from puzzlepress.cover.build import read_interior_facts
    from puzzlepress.cover.geometry import cover_geometry
    from puzzlepress.cover_template import apply_template
    from puzzlepress.cover_template_store import builtin_templates
    from puzzlepress.interior import DEFAULT_PROFILE, build_interior, print_profile, write_interior

    book = directory / "book"
    book.mkdir(parents=True, exist_ok=True)
    data = source()
    project = validate_project(data).require_project()
    (book / "book.yaml").write_text(dump_project(project), encoding="utf-8")
    files = [
        (f"shape-{seed:02d}.png", encode(line_art(seed, line=9))) for seed in range(1, DRAWINGS + 1)
    ]
    import_files(book, files)
    if cover:
        project = load_project(book).project
        build_dir = directory / "build"
        spec = print_profile(DEFAULT_PROFILE)
        write_interior(build_interior(project, spec, book), build_dir, book)  # type: ignore[arg-type]
        facts = read_interior_facts(build_dir, project)
        geometry = cover_geometry(
            facts.page_count, facts.trim_width, facts.trim_height, facts.paper
        )
        template = next(t for t in builtin_templates() if t.id == "modern-minimal")
        application = apply_template(
            template, project, geometry.spine_width, (facts.trim_width, facts.trim_height)
        )
        cover_data = application.cover.to_dict()
        cover_data["elements"] = [
            element for element in cover_data["elements"] if element.get("type") != "photo"
        ] + [
            {
                "type": "text",
                "id": "facts",
                "name": "Book facts",
                "region": "back",
                "box": {"x": 36, "y": 300, "width": 360, "height": 40},
                "text": PAGE_TEXT,
                "size": 12,
                "color": "#2b2b2b",
                "font": "sans",
            }
        ]
        data = load_project(book).project.to_dict()
        data["cover"] = cover_data
        data["cover"]["back_text"] = "Twelve synthetic drawings to color."
        data["publishing"] = publishing()
        project = validate_project(data).require_project()
        (book / "book.yaml").write_text(dump_project(project), encoding="utf-8")
        if confirm:
            confirm_all(book)
    return book


if __name__ == "__main__":
    target = Path(sys.argv[1])
    print(write_book(target))
