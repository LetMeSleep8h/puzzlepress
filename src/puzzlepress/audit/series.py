"""Earlier and sibling books: repeated puzzles and production consistency.

Earlier books are read only. Their puzzles are regenerated by the engine (the
authoritative inventory); a book that cannot be read is reported, never skipped.
"""

from collections.abc import Mapping, Sequence
from dataclasses import dataclass

from ..duplicates import WITHIN, DuplicateReport, compare_inventories
from ..inventory import Inventory
from ..models import Project
from .model import Basis, Category, Priority, Recommendation


@dataclass(frozen=True)
class OtherBook:
    """A previously loaded earlier or sibling book (read-only)."""

    label: str
    project: Project
    inventory: Inventory | None  # None for books without word searches.


def _pages(ids: Sequence[str], pages: Mapping[str, int]) -> tuple[int, ...]:
    return tuple(sorted({pages[i] for i in ids if i in pages}))


def _duplicate_recommendations(
    report: DuplicateReport, pages: Mapping[str, int]
) -> list[Recommendation]:
    found: list[Recommendation] = []
    for severity, priority, title in (
        ("exact", Priority.HIGH, "repeat a puzzle"),
        ("near", Priority.MEDIUM, "closely resemble a puzzle"),
    ):
        for within in (False, True):
            matches = [
                m
                for m in report.matches
                if m.severity == severity and (m.other_source == WITHIN) is within
            ]
            if not matches:
                continue
            ids = sorted({m.new_id for m in matches})
            pairs = "; ".join(
                f"{m.new_id} ~ {m.other_source} {m.other_id} ({len(m.shared_words)} shared words)"
                for m in matches[:8]
            ) + ("; ..." if len(matches) > 8 else "")
            where = "elsewhere in this book" if within else "an earlier book"
            found.append(
                Recommendation(
                    f"{severity}_duplicate_{'within' if within else 'previous'}",
                    priority if not within else Priority.MEDIUM,
                    Category.SERIES,
                    Basis.MEASURED,
                    f"{len(ids)} puzzle(s) {title} {where}",
                    pairs,
                    "Replace shared words (Quality lists candidates) so readers of the series "
                    "do not meet the same puzzle twice.",
                    "quality",
                    pages=_pages(ids, pages),
                    puzzles=tuple(ids),
                )
            )
    return found


def _settings(project: Project) -> dict[str, str]:
    composition = project.composition
    style = project.interior
    return {
        "author": project.book.author or "(none)",
        "imprint": project.book.imprint or "(none)",
        "language": project.book.language,
        "print profile": (project.printing.profile if project.printing else None) or "default",
        "solutions per page": str(composition.solutions.per_page) if composition else "-",
        "puzzle layout": composition.puzzle_layout.value if composition else "-",
        "interior style": "none"
        if style is None
        else f"preset {style.preset.value}"
        if style.version < 2
        else f"{style.theme.value} theme, {style.layout.value} layout",
    }


def _consistency(project: Project, others: Sequence[OtherBook]) -> list[Recommendation]:
    mine = _settings(project)
    found: list[Recommendation] = []
    for name, value in mine.items():
        different = [
            f"{other.label}: {_settings(other.project)[name]}"
            for other in others
            if _settings(other.project)[name] != value
        ]
        if not different:
            continue
        found.append(
            Recommendation(
                f"series_{name.replace(' ', '_')}",
                Priority.MEDIUM if name == "author" else Priority.LOW,
                Category.SERIES,
                Basis.JUDGMENT,
                f"Differs from earlier books: {name}",
                f"This book: {value}; " + "; ".join(different) + ".",
                "Keep series books consistent unless the difference is deliberate.",
                "settings"
                if name in ("author", "imprint", "language", "print profile")
                else "book",
            )
        )
    return found


def series_recommendations(
    project: Project,
    inventory: Inventory | None,
    others: Sequence[OtherBook],
    pages: Mapping[str, int],
) -> tuple[list[Recommendation], list[str]]:
    """Recommendations, and what could not be compared (stated, never skipped)."""
    unassessed: list[str] = []
    found: list[Recommendation] = []
    if inventory is not None:
        previous = [o.inventory for o in others if o.inventory is not None]
        skipped = [o.label for o in others if o.inventory is None]
        if skipped:
            unassessed.append(
                f"Puzzle repeats not compared with {', '.join(skipped)} (no word searches)."
            )
        report = compare_inventories(inventory, previous)
        found += _duplicate_recommendations(report, pages)
        if not report.coverage_complete:
            unassessed.append("Some puzzles could not be inventoried; repeat coverage incomplete.")
    found += _consistency(project, others)
    return found, unassessed
